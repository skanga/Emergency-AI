"""Deterministic release checks, not semantic or clinical certification.

Only recognized actions/conditions are checked. Citation identity is exact;
claim support is deliberately reported as unverified.
"""
import re

from .applicability import inapplicability_reason
from .claim_validation import check_claims
from .claim_links import insert_linked_citations
from .action_patterns import WATER_INTAKE
from .patient_facts import _breathing, _facts, _ABNORMAL, _SWALLOW, _UNSAFE_SWALLOW, _CONDITIONAL
from .query_planner import normalize, plan_query, _consciousness

_CITATION = re.compile(r'\[S([1-9][0-9]*)\]')
_REFERENCE = re.compile(r'\[(?:[Ss][^\]\n]*|\^?\d[^\]\n]*)\]')
_FOOTNOTE = re.compile(r'\[(\d+(?:\s*[,–-]\s*\d+)*)\]')
_CPR = re.compile(r'\b(?:cpr|rcp|cardiopulmonary resuscitation|chest compressions|compressoes toracicas|compresiones toracicas)\b')
_ACTION = re.compile(r'\b(?:start|begin|perform|give|do(?= cpr)|initiate|continue|administer|offer|take|drink|feed|inicie|iniciar|faca|realize|comece|dar|tome|beba|ofereca|ofrezca(?:le)?|ofrecer|administre|comience|inicia|haga|realizar|dele)\b')
_ORAL = re.compile(r'\b(?:oral|by mouth|tablet\w*|pill\w*|antihistamine\w*|antihistaminico\w*|comprimido\w*|pastilla\w*|por boca|pela boca|glucose|glicose|glucosa|sugar|acucar|azucar|honey|mel|miel|juice|suco|zumo|jugo|food|drink|alimento\w*|bebida\w*)\b')
_INFANT_WRONG = re.compile(r'\b(?:pinch\w*|aperte|apertar|pince|pincez|pelliz\w*|tape)\b.{0,35}\b(?:nose|nariz)\b|\b(?:compressions only|only compressions|somente compressoes|solo compresiones)\b')


def source_for_prompt(text):
    """Original source footnotes are not application evidence identifiers."""
    text = _FOOTNOTE.sub(lambda m: '(source note ' + m[1] + ')', text)
    return _CITATION.sub(lambda m: '(source marker S' + m[1] + ')', text)


def _negative_action(text, match):
    prefix = text[:match.start()]
    return bool(re.search(r'\b(?:do not|don t|never|must not|nao|nunca|no)\s+(?:(?:attempt to|try to|tente|intente)\s+)?$', prefix))


def _cpr_condition(text, facts):
    if not _CONDITIONAL.search(text):
        return False
    state_value = _consciousness(text) or facts['consciousness']
    breath_value = _breathing(text) or facts['breathing']
    if state_value != 'unresponsive' or breath_value != 'abnormal':
        return False
    state = re.search(r'\b(?:unresponsive|unconscious|inconsciente|nao responde|no responde)\b', text)
    breath = _ABNORMAL.search(text)
    if state and breath:
        between = text[min(state.end(), breath.end()):max(state.start(), breath.start())]
        if re.search(r'\b(?:or|ou|o)\b', between):
            return False
    return True


def _action_issues(answer, plan):
    facts = _facts(plan)
    issues = []
    # Reuse the admission boundary for clinical instructions regenerated by the
    # model. Do not treat the question's topic as evidence for those instructions.
    reason = inapplicability_reason({'text':answer}, plan)
    if reason and reason.startswith(('clinical_', 'invasive_')):
        issues.append(reason)
    lines = answer.splitlines()
    for index, line in enumerate(lines):
        citation_scope = line
        if re.match(r'^\s*#{1,6}\s', line):
            for following in lines[index + 1:]:
                if re.match(r'^\s*#{1,6}\s', following):
                    break
                citation_scope += '\n' + following
        for sentence in re.split(r';|(?<=[.!?])\s+', line):
            t = normalize(re.sub(r'\b(?:dê|dé)\b', 'give', _CITATION.sub('', sentence), flags=re.I))
            actions = [m for m in _ACTION.finditer(t) if not _negative_action(t, m)
                       and not (m[0] == 'drink' and re.search(r'\b(?:food|or|and|any)\s*$', t[:m.start()]))]
            cpr = bool(_CPR.search(t) and (actions or re.search(r'\b(?:cpr|rcp) (?:immediately|now|agora|ahora|imediatamente|inmediatamente)\b', t)))
            patient_context = bool(plan.topics or facts['consciousness'] or facts['swallowing']
                                   or re.search(r'\b(?:glucose|glicose|glucosa|tablet\w*|antihistamine\w*|antihistaminico\w*)\b', t))
            water = any(not _negative_action(t, m) for m in WATER_INTAKE.finditer(t))
            oral = bool(patient_context and ((_ORAL.search(t) and actions) or water))
            infant_wrong = _INFANT_WRONG.search(t)
            if infant_wrong and facts['age_group'] in ('infant', 'neonatal') and not _negative_action(t, infant_wrong):
                issues.append('infant_technique_mismatch')
            if cpr:
                known = facts['consciousness'] == 'unresponsive' and facts['breathing'] == 'abnormal'
                # A stated condition must itself be sound even when the patient
                # currently meets the prerequisites (avoid teaching an OR rule).
                patient_condition = _CONDITIONAL.search(t) and (_consciousness(t) or _breathing(t))
                if not (_cpr_condition(t, facts) if patient_condition else known):
                    issues.append('cpr_prerequisites_missing')
            if oral:
                conditional = bool(_CONDITIONAL.search(t) and _consciousness(t) == 'responsive'
                                   and _SWALLOW.search(t) and not _UNSAFE_SWALLOW.search(t))
                known = facts['consciousness'] == 'responsive' and facts['swallowing'] == 'safe'
                if conditional:
                    state = re.search(r'\b(?:awake|conscious|responsive|alert|acordad[oa]|consciente|despiert[oa])\b', t)
                    swallow = _SWALLOW.search(t)
                    between = t[min(state.end(), swallow.end()):max(state.start(), swallow.start())] if state else 'or'
                    conditional = not re.search(r'\b(?:or|ou|o)\b', between)
                patient_condition = _CONDITIONAL.search(t) and (_consciousness(t) or _SWALLOW.search(t))
                if facts['swallowing'] == 'unsafe' or not (conditional if patient_condition else known):
                    issues.append('oral_intake_prerequisites_missing')
            if (cpr or oral or infant_wrong) and not _CITATION.search(citation_scope):
                issues.append('action_citation_missing')
    return list(dict.fromkeys(issues)), facts


def validate_answer(answer, sources, question, lang='en', history=None):
    available = {str(s['n']): s['n'] for s in sources if not s.get('context_omitted')}
    plan = plan_query(question, lang, history)
    # Code examples are not references. Do not exempt code in emergency topics;
    # the action checks also inspect the original text regardless of formatting.
    citation_text = answer if plan.topics else re.sub(r'```[\s\S]*?```|`[^`\n]+`', lambda m: ' ' * len(m[0]), answer)
    issues, cited = [], []
    for marker in _REFERENCE.finditer(citation_text):
        match = _CITATION.fullmatch(marker[0])
        if not match:
            issues.append('invalid_citation_format')
        elif match[1] not in available:
            issues.append('citation_not_supplied')
        elif citation_text[marker.end():].lstrip().startswith(('(', '[')) and not citation_text[marker.end():].lstrip().startswith('[S'):
            issues.append('citation_link_override')
        elif marker.start() and citation_text[marker.start()-1] in '!\\':
            issues.append('invalid_citation_format')
        else:
            cited.append(available[match[1]])
    # Catch unfinished citation syntax as well as complete invalid markers.
    if re.search(r'\[S', _REFERENCE.sub('', citation_text), re.I):
        issues.append('invalid_citation_format')
    action_issues, facts = _action_issues(answer, plan)
    issues.extend(action_issues)
    claim_issues, claim_checks = check_claims(answer, sources, plan)
    issues.extend(claim_issues)
    result = {'status':'blocked' if issues else 'passed', 'issues':list(dict.fromkeys(issues)),
              'citation_ids':sorted(set(cited)), 'claim_support':'not_verified',
              'action_conditions':'known_patterns_only', 'patient_facts':facts,
              'claim_checks':claim_checks}
    # Nothing from the model is released if any part fails validation.
    linked_answer = insert_linked_citations(answer, claim_checks['claims']) if not issues else answer
    rendered = '' if issues else _CITATION.sub(lambda m: '[' + m[1] + ']' if plan.topics or citation_text[m.start():m.end()] == m[0] else m[0], linked_answer)
    return rendered, result


